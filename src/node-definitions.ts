export function createGraphNodeFromDefinition(
  def: NodeDefinition,
  x: number,
  y: number,
  customId?: string
): GraphNode {
  return {
    id:
      customId ||
      `node-${def.type}-${Date.now().toString(36)}-${Math.random()
        .toString(36)
        .substring(2, 6)}`,
    type: def.type,
    title: def.title,
    category: def.expressionType,
    expressionType: def.expressionType,
    expressionGroup: def.expressionGroup,
    isExtension: def.isExtension,
    groups: def.groups,
    subtitle: def.subtitle,
    description: def.description,
    x,
    y,
    inputs: def.inputs.map((inp) => ({
      ...inp,
      direction: "input" as const,
      value: inp.defaultValue,
    })),
    outputs: def.outputs.map((out) => ({
      ...out,
      direction: "output" as const,
    })),
    properties: def.defaultProperties
      ? JSON.parse(JSON.stringify(def.defaultProperties))
      : undefined,
  };
}
